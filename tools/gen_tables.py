"""Generates data tables from pyembroidery 1.5.1 (MIT, see THIRD_PARTY_NOTICES.md).

usage: python -I tools/gen_tables.py <repo root>     (with pyembroidery installed)

Writes:
  crates/openstitch-core/src/charts.rs                       PEC, JEF, SEW, HUS and SHV thread charts
  crates/openstitch-formats/tests/fixtures/pec_blank_icon.bin  empty 48x38 PEC icon frame
"""
import os
import sys

from pyembroidery.EmbThreadJef import get_thread_set as jef_set
from pyembroidery.EmbThreadPec import get_thread_set as pec_set
from pyembroidery.EmbThreadSew import get_thread_set as sew_set
from pyembroidery.EmbThreadHus import get_thread_set as hus_set
from pyembroidery.EmbThreadShv import get_thread_set as shv_set
from pyembroidery.PecGraphics import get_blank

root = sys.argv[1]
out = [
    "// Generated by tools/gen_tables.py from pyembroidery 1.5.1 (MIT License, see THIRD_PARTY_NOTICES.md).",
    "// `None` marks a chart index the format leaves unused (index 0 of PEC and JEF); SEW index 0 is",
    "// the real \"Unknown\" entry. HUS and SHV have no unused entries.",
    "",
    "use crate::Thread;",
    "",
]
for const, threads, brand in (("PEC_CHART", pec_set(), "Brother"), ("JEF_CHART", jef_set(), "Janome"), ("SEW_CHART", sew_set(), "Janome"),
                              ("HUS_CHART", hus_set(), "Husqvarna Viking"), ("SHV_CHART", shv_set(), "Husqvarna Viking")):
    out.append(f"pub static {const}: [Option<Thread>; {len(threads)}] = [")
    for t in threads:
        if t is None:
            out.append("    None,")
        else:
            out.append(
                f'    Some(Thread::chart({t.get_red()}, {t.get_green()}, {t.get_blue()}, '
                f'"{t.description}", "{t.catalog_number}", "{brand}")),'
            )
    out += ["];", ""]
with open(os.path.join(root, "crates/openstitch-core/src/charts.rs"), "w") as f:
    f.write("\n".join(out))

fixtures = os.path.join(root, "crates/openstitch-formats/tests/fixtures")
os.makedirs(fixtures, exist_ok=True)
with open(os.path.join(fixtures, "pec_blank_icon.bin"), "wb") as f:
    f.write(bytes(get_blank()))
print("ok", len(pec_set()), len(jef_set()), len(sew_set()), len(hus_set()), len(shv_set()), len(get_blank()))
